"""Experiment ETH-B03: commutative swap optimum vs. general (non-commutative) min-rank
for the routing support pattern of the ETH refutation (OpenAI 378, Sec. 2.6, Step 2).

Index set B = ([r]x[r])^Q, u = (a_u, d_u) with a_u, d_u in [r]^Q.
Support pattern P: (u,w) allowed iff Ham(d_u, a_w) <= R-1.
We want M supported on P minimising rank(I - M)  (= number of measurements c).

* commutative optimum (paper's family M = V0 f(W0), and in fact any element of the algebra
  generated by the commuting swaps, i.e. arbitrary gamma_S): equals
      min_h  sum_{y : h(y) != (-1)^{|y|}}  d_-^{|y|} d_+^{Q-|y|},  deg h <= R-1.
* general optimum: min rank of a partial matrix (I off the pattern). We find upper bounds with
  alternating projections (heuristic, numerically verified by singular values).
"""
import itertools, sys
import numpy as np

def commutative_opt(Q, R, r):
    dp, dm = r * (r + 1) // 2, r * (r - 1) // 2
    ys = list(itertools.product([0, 1], repeat=Q))
    w = np.array([dm ** sum(y) * dp ** (Q - sum(y)) for y in ys], dtype=float)
    par = np.array([(-1) ** sum(y) for y in ys], dtype=float)
    mons = [S for k in range(R) for S in itertools.combinations(range(Q), k)]
    V = np.array([[np.prod([y[i] for i in S]) if S else 1 for S in mons] for y in ys], float)
    best = (w.sum(), None)
    n = len(ys)
    for mask in range(1, 1 << n):
        idx = [i for i in range(n) if mask >> i & 1]
        wt = w[idx].sum()
        if w.sum() - wt >= best[0]:
            continue
        A = V[idx]
        sol, *_ = np.linalg.lstsq(A, par[idx], rcond=None)
        if np.allclose(A @ sol, par[idx], atol=1e-9):
            best = (w.sum() - wt, idx)
    return int(round(best[0])), int(w.sum())

def pattern(Q, R, r):
    labels = list(itertools.product(range(r), repeat=2 * Q))  # a(0..Q-1), d(0..Q-1)
    a = np.array([l[:Q] for l in labels]); d = np.array([l[Q:] for l in labels])
    ham = (d[:, None, :] != a[None, :, :]).sum(-1)
    return ham <= R - 1, len(labels)

def altproj(P, k, iters=3000, seed=0):
    D = P.shape[0]
    rng = np.random.default_rng(seed)
    I = np.eye(D)
    A = I + rng.standard_normal((D, D)) * P * 0.1
    for _ in range(iters):
        U, s, Vt = np.linalg.svd(A)
        Ak = (U[:, :k] * s[:k]) @ Vt[:k]
        A = np.where(P, Ak, I)          # entries off the pattern are forced to I
    s = np.linalg.svd(A, compute_uv=False)
    return s[k] / s[0] if k < D else 0.0, A

if __name__ == "__main__":
    for (Q, R, r) in [(2, 2, 2), (3, 2, 2), (3, 3, 2), (2, 2, 3)]:
        c_comm, D = commutative_opt(Q, R, r)
        P, D2 = pattern(Q, R, r)
        assert D == D2
        # search downward from the commutative optimum
        found = c_comm
        for k in range(c_comm - 1, 0, -1):
            best = min(altproj(P, k, iters=1500, seed=s)[0] for s in range(3))
            if best < 1e-8:
                found = k
            else:
                break
        print(f"Q={Q} R={R} r={r} D={D}: commutative optimum rank={c_comm}; "
              f"general (alt-proj upper bound) rank={found}", flush=True)
